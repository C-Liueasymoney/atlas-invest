import { z } from "zod";
import type { ProviderDefinition } from "../types";
import { AppError } from "../errors";
const configSchema = z.object({
  ttlSeconds: z.number().int().min(30).max(86400),
  perMinute: z.number().int().min(1).max(1000),
  perHour: z.number().int().min(1).max(10000),
  perDay: z.number().int().min(1).max(100000),
});
function provider(
  id: string,
  displayName: string,
  category: string,
  docsUrl: string,
  authMode: string,
  assetClasses: string[],
  operations: string[],
  intervals: string[],
  latency: string,
  envVar?: string,
  perDay = 1000,
  enabled = true,
  licenseNote = "仅供个人研究；调用权益和再分发许可请核对官方条款。",
): ProviderDefinition {
  return {
    id,
    displayName,
    category,
    docsUrl,
    termsUrl: docsUrl,
    configurationSchema: configSchema,
    capabilities: {
      assetClasses,
      operations,
      intervals,
      authMode,
      latency,
      supportsBatch: false,
      termsUrl: docsUrl,
    },
    envVar,
    enabled,
    licenseNote,
    config: {
      ttlSeconds: id === "gold_api" ? 30 : 300,
      perMinute: 5,
      perHour: 100,
      perDay,
    },
  };
}
